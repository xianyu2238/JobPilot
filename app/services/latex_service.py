"""Fill the licensed OpenCurve template and compile a saved resume locally."""

from io import BytesIO
import logging
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import threading
from uuid import uuid4
import zipfile

from jinja2 import Environment, FileSystemLoader, StrictUndefined
import pymupdf

from app.core.config import Settings
from app.core.errors import AppError
from app.repositories.memory import MemoryRepository
from app.schemas.business import ResumeResponse
from app.schemas.export import ExportArtifact, ExportRequest, ExportResponse

ROOT = Path(__file__).resolve().parents[2]
TEMPLATES = ROOT / "app" / "templates" / "opencurve"
logger = logging.getLogger("jobpilot.export")
ESCAPES = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "$": r"\$", "&": r"\&",
           "#": r"\#", "%": r"\%", "_": r"\_", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def latex_escape(text: str | None) -> str:
    value = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]", "", text or "")
    return re.sub(r"[\\{}$&#%_~^]", lambda match: ESCAPES[match.group()], value)


def content_lines(text: str) -> list[str]:
    return [latex_escape(re.sub(r"^\s*[-*•]\s+", "", line.strip())) for line in text.splitlines() if line.strip()]


def render_sources(resume: ResumeResponse, layout: str = "standard") -> dict[str, bytes]:
    """Only user data is escaped; all TeX commands come from fixed templates."""
    parsed = resume.parsed_data
    info = parsed.personal_info
    contacts = [latex_escape(value.replace("\n", " ")) for value in (info.phone, info.email, info.city) if value]
    context = {
        "line_spacing": "1.08" if layout == "compact" else "1.2",
        "personal": {"name": latex_escape(info.name or "个人简历"), "contacts": r"\headerdivider ".join(contacts),
                     "job_intention": latex_escape(info.job_intention), "other_lines": content_lines(info.other or "")},
        **{field: [{"title": latex_escape(item.title), "lines": content_lines(item.description)} for item in getattr(parsed, field)]
           for field in ("education", "experiences", "projects")},
        "skills": [{"name": latex_escape(item.name), "lines": content_lines(item.description)} for item in parsed.skills],
    }
    environment = Environment(
        loader=FileSystemLoader(TEMPLATES), undefined=StrictUndefined, autoescape=False,
        variable_start_string="<<", variable_end_string=">>", block_start_string="<%", block_end_string="%>",
        comment_start_string="<#", comment_end_string="#>", trim_blocks=True, lstrip_blocks=True,
        keep_trailing_newline=True,
    )
    mapping = {"resume.tex": "resume.tex.j2", "sections/education.tex": "education.tex.j2",
               "sections/experience.tex": "experience.tex.j2", "sections/projects.tex": "projects.tex.j2",
               "sections/skills.tex": "skills.tex.j2"}
    sources = {name: environment.get_template(template).render(context).encode("utf-8") for name, template in mapping.items()}
    for name in ("open-curve.sty", "jobpilot-layout.tex", "LICENSE", "UPSTREAM.md"):
        sources[name] = (TEMPLATES / name).read_bytes()
    sources["README.txt"] = (
        "Generated by JobPilot from saved resume revision " + str(resume.revision) + ".\n"
        "Compile: xelatex -no-shell-escape -interaction=nonstopmode -halt-on-error resume.tex\n"
        "Or: tectonic -X compile --untrusted resume.tex\n"
        "Requires CurVe, ctex, fontspec, fontawesome5 and tcolorbox; TeX Live includes these packages.\n"
        "OpenCurve upstream attribution and MIT license: UPSTREAM.md / LICENSE.\n"
    ).encode("utf-8")
    return sources


def source_archive(sources: dict[str, bytes]) -> bytes:
    buffer = BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, content in sources.items():
            archive.writestr(name, content)
    return buffer.getvalue()


class LatexExporter:
    def __init__(self, settings: Settings, store: MemoryRepository, runner=None):
        self.settings, self.store = settings, store
        self.runner = runner if runner is not None else subprocess.run
        self._lock = threading.Lock()

    def snapshot(self, resume_id: str, request: ExportRequest) -> ResumeResponse:
        resume = self.store.get(resume_id, "resume").response
        if resume.revision != request.expected_revision:
            raise AppError(409, "RESUME_VERSION_CONFLICT", "简历已更新，请重新加载已保存版本后导出。")
        if resume.parse_status == "text_ready":
            raise AppError(409, "RESUME_NOT_STRUCTURED", "请先整理或手动填写简历并保存，再导出。")
        return resume

    def source(self, resume_id: str, request: ExportRequest) -> bytes:
        resume = self.snapshot(resume_id, request)
        result = source_archive(render_sources(resume, request.layout))
        self.snapshot(resume_id, request)
        return result

    def engine(self) -> tuple[str, str]:
        configured = self.settings.latex_binary
        if configured:
            path = Path(configured)
            resolved = str(path.resolve()) if path.is_file() else shutil.which(configured)
            if not resolved:
                raise AppError(503, "LATEX_NOT_AVAILABLE", "配置的 LaTeX 编译器不存在，请检查 JOBPILOT_LATEX_BINARY。")
            mode = self.settings.latex_engine
            if mode == "auto":
                mode = "tectonic" if "tectonic" in Path(resolved).stem.lower() else "xelatex"
            return mode, resolved
        for mode in ([self.settings.latex_engine] if self.settings.latex_engine != "auto" else ["xelatex", "tectonic"]):
            installed = shutil.which(mode)
            bundled = ROOT / ".tools" / "tectonic" / ("tectonic.exe" if os.name == "nt" else "tectonic")
            if installed:
                return mode, installed
            if mode == "tectonic" and bundled.is_file():
                return mode, str(bundled)
        raise AppError(503, "LATEX_NOT_AVAILABLE", "未找到 LaTeX 编译器，请运行 scripts/setup_latex.py 并预热依赖，或配置已有 XeLaTeX。仍可下载 LaTeX 源文件。")

    def build(self, sources: dict[str, bytes]) -> tuple[bytes, int, list[str]]:
        mode, binary = self.engine()
        cache = ROOT / ".tools" / "tectonic" / "cache"
        cache.mkdir(parents=True, exist_ok=True)
        env = os.environ.copy()
        env.update(TECTONIC_CACHE_DIR=str(cache), TECTONIC_UNTRUSTED_MODE="1", openin_any="p", openout_any="p")
        if self.settings.latex_proxy:
            env["HTTPS_PROXY"] = self.settings.latex_proxy
            env["HTTP_PROXY"] = self.settings.latex_proxy
        with tempfile.TemporaryDirectory(prefix="jobpilot-latex-") as directory:
            work = Path(directory)
            for name, content in sources.items():
                target = work / name
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(content)
            if mode == "tectonic":
                command = [binary, "-X", "compile", "--untrusted", "--keep-logs"]
                if not self.settings.latex_allow_downloads:
                    command.append("--only-cached")
                command += ["--outdir", str(work), "resume.tex"]
                runs = 1
            else:
                command = [binary, "-no-shell-escape", "-interaction=nonstopmode", "-halt-on-error", "-file-line-error", "resume.tex"]
                runs = 2
            for _ in range(runs):
                try:
                    result = self.runner(command, cwd=work, env=env, capture_output=True, timeout=self.settings.latex_timeout_seconds,
                                         creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
                except subprocess.TimeoutExpired:
                    raise AppError(504, "LATEX_TIMEOUT", "PDF 编译超时，请精简内容或检查 LaTeX 环境。") from None
                except OSError:
                    raise AppError(503, "LATEX_NOT_AVAILABLE", "无法启动 LaTeX 编译器，请检查安装路径和运行权限。") from None
                if result.returncode:
                    logger.warning("latex_compile_failed engine=%s return_code=%s", mode, result.returncode)
                    output = result.stderr + result.stdout
                    if mode == "tectonic" and (b"cached" in output.lower() or b"bundle" in output.lower()):
                        raise AppError(503, "LATEX_DEPENDENCIES_MISSING", "LaTeX 依赖未缓存，请先运行 scripts/warm_latex.py；也可先下载 LaTeX 源文件。")
                    raise AppError(502, "LATEX_COMPILE_FAILED", "LaTeX 编译失败，请检查字体或宏包配置；可下载源文件在本地排查。")
            pdf_path = work / "resume.pdf"
            if not pdf_path.is_file() or pdf_path.stat().st_size > 20 * 1024 * 1024:
                raise AppError(502, "LATEX_OUTPUT_INVALID", "编译器未产生有效 PDF，或输出文件超过 20 MiB。")
            pdf = pdf_path.read_bytes()
            try:
                with pymupdf.open(stream=pdf, filetype="pdf") as document:
                    pages = document.page_count
                    if not pages:
                        raise ValueError("empty PDF")
            except (RuntimeError, ValueError):
                raise AppError(502, "LATEX_OUTPUT_INVALID", "编译器返回的 PDF 无法读取。") from None
            warnings = []
            if pages > 1:
                warnings.append(f"当前简历共 {pages} 页，内容已完整保留；可选择紧凑排版或调整内容。")
            log = (work / "resume.log").read_text(encoding="utf-8", errors="replace") if (work / "resume.log").exists() else ""
            if "Overfull \\hbox" in log:
                warnings.append("部分文字可能超出行宽，请检查下载后的 PDF 并调整长标题或换行。")
            if "Missing character" in log:
                warnings.append("部分字符可能缺少字体，请检查 PDF 中的符号。")
            return pdf, pages, warnings

    def create(self, resume_id: str, request: ExportRequest) -> ExportResponse:
        resume = self.snapshot(resume_id, request)
        cached = self.store.get(resume_id, "resume").export
        if cached and cached.revision == resume.revision and cached.layout == request.layout:
            return self.metadata(resume_id, cached)
        if not self._lock.acquire(blocking=False):
            raise AppError(429, "EXPORT_BUSY", "已有 PDF 正在生成，请稍后重试。")
        try:
            sources = render_sources(resume, request.layout)
            pdf, pages, warnings = self.build(sources)
            artifact = ExportArtifact(uuid4().hex, resume.revision, request.layout, pdf, source_archive(sources), pages, warnings)
            self.store.save_export(resume_id, artifact)
            return self.metadata(resume_id, artifact)
        finally:
            self._lock.release()

    def download(self, resume_id: str, export_id: str) -> ExportArtifact:
        record = self.store.get(resume_id, "resume")
        artifact = record.export
        if not artifact or artifact.export_id != export_id or artifact.revision != record.response.revision:
            raise AppError(404, "EXPORT_NOT_FOUND", "导出结果不存在或已因简历修改而失效，请重新导出。")
        return artifact

    @staticmethod
    def metadata(resume_id: str, artifact: ExportArtifact) -> ExportResponse:
        return ExportResponse(export_id=artifact.export_id, resume_id=resume_id, revision=artifact.revision,
                              layout=artifact.layout, page_count=artifact.page_count, warnings=artifact.warnings,
                              filename=f"jobpilot-resume-r{artifact.revision}.pdf")
